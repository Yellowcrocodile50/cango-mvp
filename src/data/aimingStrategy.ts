/* ── 질문 ────────────────────────────────────────────────────
   축이 다섯이다.

   agg   공격성. 위로 지를 수 있는 여력 → **사다리 위치**
   floor 안정 수용도. 안정권 대학에 실제로 갈 의향 → **안정 장수 후처리**
   intv  논술·면접 여력 → **면접 개수 상한 + 논술 갈래 판정**
   gyo   내신 강점 → **교과 갈래 판정**
   rec   생기부 강점 → **학종 갈래 판정**

   ⚠️ 유형을 10개로 늘리면서 축을 둘 더 만들었다. 공격성 한 축을 10칸으로 쪼개면
   옆 유형과 상향 1장 차이라 이름만 다른 유형이 된다. 유형을 늘리는 건
   칸을 쪼개는 일이 아니라 **축을 늘리는 일**이다.

   ⚠️ agg와 floor는 반드시 분리한다. "안 갈 곳은 쓰기 싫다"가 공격성을 올리면
   정시도 약하고 안정권도 못 쓰는 가장 위험한 학생이 공격형으로 분류된다.

   📌 floor는 **음수도 준다**(Q4b 수시 납치). 안정을 "덜 받아들인다"는 답이 있어야
   Q2 하나로만 안정 장수가 정해지는 걸 막을 수 있다. MAX_FLOOR는 선택지별 최댓값의
   합이라 음수를 넣어도 6으로 유지된다. */

